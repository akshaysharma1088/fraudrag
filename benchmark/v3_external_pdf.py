"""FraudRAG Benchmark v3: third-party *synthetic* PDF robustness experiment.

The five publicly released Bankstatemently PDFs are synthetically generated by
their publisher; transaction ground-truth answers are NOT publicly released.
This script never pretends that the PDFs show actual bank fraud.

Use only the five source PDFs at a pinned upstream commit; check published
SHA256 exactly before extracting. Make explicit *text-level controlled edits*
from extracted text, never altered bank PDFs. The original extracted text is
a deliberate complete-reference oracle, not a realistic independent ledger.

No LLM is needed for this ingestion/scoring experiment. All source documents
remain in a gitignored local cache and are not re-uploaded.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import re
import unicodedata
import urllib.request
from pathlib import Path

SOURCE_COMMIT = "2d8d31d68dcedbf9028b87f6c7df286f53a6c7de"
SOURCE_REPO = "bankstatemently/bank-statement-parsing-benchmark"
SOURCE_ROOT = ("https://raw.githubusercontent.com/" + SOURCE_REPO + "/"
               + SOURCE_COMMIT + "/datasets/basic/")
EXPECTED_SHA256 = {
    "bsb-001": "d3d5071b90a33272f31bab5c5660d78b2ae29d2c6e1720477f5e8b167f73e843",
    "bsb-002": "3700a073ac1262173cbabbd5667cd3a59e04cf0b14e3a865ae25ce21089ab97d",
    "bsb-003": "4945bcda107e6d7845850e728b90c4dba1cb11de5a13356b0794df349e5527c2",
    "bsb-004": "67a5b862696fc06e675db53867be6fcc71a4ecc13998193e8b45e2cd63371051",
    "bsb-005": "a5cc2a7d210bc657c55b44ac159c5d10b2d71553f3646ce17a64051f918fd960",
}
MAX_SOURCE_BYTES = 2_000_000
MONEY = re.compile(r"(?<![\w])(?:\d{1,3}(?:[ ,]\d{3})+|\d+)[.,]\d{2}(?!\d)")
CASES = ("unchanged", "benign_spacing", "edited_first_amount", "edited_later_amount")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def verified_source(source_id: str, cache: Path) -> tuple[bytes, str]:
    if source_id not in EXPECTED_SHA256:
        raise ValueError("Unregistered source ID; refusing arbitrary URL")
    path = cache / (source_id + "-statement.pdf")
    if not path.exists():
        cache.mkdir(parents=True, exist_ok=True)
        url = f"{SOURCE_ROOT}{source_id}/{source_id}-statement.pdf"
        request = urllib.request.Request(url, headers={"User-Agent": "FraudRAG-research-v3/1.0"})
        with urllib.request.urlopen(request, timeout=120) as response:
            size = response.headers.get("Content-Length")
            if size and int(size) > MAX_SOURCE_BYTES:
                raise ValueError("Source PDF exceeds allowed size")
            raw = response.read(MAX_SOURCE_BYTES + 1)
        if len(raw) > MAX_SOURCE_BYTES:
            raise ValueError("Source PDF too large")
        if sha256(raw) != EXPECTED_SHA256[source_id]:
            raise ValueError(f"Upstream PDF hash changed for {source_id}; no extraction")
        if not raw.startswith(b"%PDF"):
            raise ValueError("Source is not a PDF")
        path.write_bytes(raw)
    raw = path.read_bytes()
    if sha256(raw) != EXPECTED_SHA256[source_id]:
        raise ValueError(f"Cached source PDF hash mismatch for {source_id}")
    return raw, f"{SOURCE_ROOT}{source_id}/{source_id}-statement.pdf"


def extract_pdf(raw: bytes) -> tuple[str, dict]:
    import pdfplumber
    with pdfplumber.open(io.BytesIO(raw)) as doc:
        page_chars = []
        pages = []
        for idx, page in enumerate(doc.pages, start=1):
            text = page.extract_text(layout=False) or ""
            pages.append({"page": idx, "chars": len(text),
                          "has_selectable_text": bool(text.strip())})
            page_chars.append(text)
    return "\n".join(page_chars), {"page_count": len(pages), "pages": pages}


def normalize(value: str) -> str:
    return " ".join(unicodedata.normalize("NFKC", value).split())


def mutate_number(value: str) -> str:
    # Change only one digit of a monetary-looking string; preserve separators
    # and digit length to avoid easy shortcuts from format changes alone.
    digits = [i for i, char in enumerate(value) if char.isdigit()]
    if not digits:
        raise ValueError("No mutable digits")
    pos = digits[-1]                  # cents digit, intentionally subtle
    replacement = "0" if value[pos] != "0" else "1"
    return value[:pos] + replacement + value[pos+1:]


def create_variants(source_id: str, extracted: str) -> tuple[list[dict], list[dict]]:
    """Return controlled variants and exclusions, without inventing labels."""
    variants = [{
        "case_id": f"{source_id}:unchanged",
        "source_id": source_id, "edit_type": "unchanged",
        "injected_change": 0, "text": extracted,
        "ground_truth_origin": "original publisher PDF extraction"
    }]
    exclusions = []
    match = re.search(r"\s+", extracted)
    if match:
        # Exactly meaning-preserving whitespace edit for an extraction negative.
        benign = extracted[:match.start()] + "   " + extracted[match.end():]
        variants.append({
            "case_id": f"{source_id}:benign_spacing",
            "source_id": source_id, "edit_type": "benign_spacing",
            "injected_change": 0, "text": benign,
            "ground_truth_origin": "deterministic format-only edit, NOT a fraud label"
        })
    else:
        exclusions.append({"source_id": source_id, "case": "benign_spacing",
                           "reason": "No whitespace to normalize"})
    matches = list(MONEY.finditer(extracted))
    if not matches:
        exclusions.append({"source_id": source_id, "case": "amount_edits",
                           "reason": "No parseable amount tokens in extracted PDF"})
    for index, label in ((0, "edited_first_amount"), (-1, "edited_later_amount")):
        if not matches:
            break
        match = matches[index]
        if label == "edited_later_amount" and len(matches) < 2:
            exclusions.append({"source_id": source_id, "case": label,
                               "reason": "Fewer than two amount tokens"})
            continue
        altered = extracted[:match.start()] + mutate_number(match.group()) + extracted[match.end():]
        if altered == extracted:
            raise AssertionError("Controlled edit had no effect")
        variants.append({
            "case_id": f"{source_id}:{label}",
            "source_id": source_id, "edit_type": label,
            "injected_change": 1, "text": altered,
            "ground_truth_origin": "controlled perturbation to extracted PDF text; NOT a fraud label"
        })
    return variants, exclusions


def classify(submitted: str, original: str | None, mode: str):
    if mode == "no_source":
        return None
    if original is None:
        raise ValueError("Expected verified extracted original")
    if mode == "full_original":
        return int(normalize(submitted) != normalize(original))
    if mode == "first_30_tokens":
        # Compare lexical units, not character offsets. Harmless spacing changes
        # must never shift the truncation boundary and cause a false alarm.
        # A match on an incomplete reference is ALWAYS inconclusive.
        source_prefix = normalize(original).split()[:30]
        submitted_prefix = normalize(submitted).split()[:30]
        return 1 if submitted_prefix != source_prefix else None
    raise ValueError(mode)


def rates(rows: list[dict], predictions: list[int | None]) -> dict:
    if len(rows) != len(predictions):
        raise ValueError("Missing evaluation rows")
    tp = tn = fp = fn = abstentions = 0
    for row, pred in zip(rows, predictions):
        truth = int(row["injected_change"])
        if pred is None:
            abstentions += 1
            if truth:
                fn += 1
            else:
                fp += 1
        elif pred == 1:
            if truth:
                tp += 1
            else:
                fp += 1
        else:
            if truth:
                fn += 1
            else:
                tn += 1
    precision = tp/(tp+fp) if tp+fp else 0
    recall = tp/(tp+fn) if tp+fn else 0
    return {"n": len(rows), "tp": tp, "tn": tn, "fp": fp, "fn": fn,
            "abstentions": abstentions, "accuracy_with_abstentions_as_errors": (tp+tn)/len(rows),
            "precision": precision, "recall": recall,
            "f1": 2*precision*recall/(precision+recall) if precision+recall else 0}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--cache", default="data/external_v3")
    p.add_argument("--out", default="artifacts/benchmark_v3")
    args = p.parse_args()
    cache, out = Path(args.cache), Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    full_rows, variant_rows, exclusions, predictions = [], [], [], []
    originals = {}
    for sid in EXPECTED_SHA256:
        raw, url = verified_source(sid, cache)
        extracted, meta = extract_pdf(raw)
        if not extracted.strip():
            exclusions.append({"source_id": sid, "case": "all",
                               "reason": "No selectable text; requires independently validated OCR"})
            continue
        originals[sid] = extracted
        full_rows.append({
            "source_id": sid, "source_pdf_sha256": sha256(raw), "source_url": url,
            "extracted_text_sha256": sha256(extracted.encode("utf8")),
            "page_count": meta["page_count"],
            "selectable_text_pages": sum(x["has_selectable_text"] for x in meta["pages"]),
            "extracted_characters": len(extracted),
            "recognized_amount_tokens": len(list(MONEY.finditer(extracted))),
            "all_source_pdfs_are_publisher_synthetic": True,
        })
        variants, reasons = create_variants(sid, extracted)
        exclusions.extend(reasons)
        variant_rows.extend(variants)
    if not full_rows:
        raise ValueError("No verifiably extracted released PDF; no experiment result")
    if len(full_rows) != len(EXPECTED_SHA256):
        # Source coverage is scientifically material; don't call partial
        # success a validated five-PDF benchmark.
        raise ValueError(f"Only {len(full_rows)}/5 sources had selectable text")
    for mode in ("full_original", "first_30_tokens", "no_source"):
        for row in variant_rows:
            pred = classify(row["text"], originals[row["source_id"]], mode)
            predictions.append({
                "case_id": row["case_id"], "source_id": row["source_id"],
                "test_condition": mode, "true_controlled_edit": row["injected_change"],
                "predicted_edit": "ABSTAIN" if pred is None else pred
            })
    summary = {
        "name": "FraudRAG Benchmark v3 third-party synthetic-PDF robustness pilot",
        "source_upstream_commit": SOURCE_COMMIT,
        "license_at_source": "MIT; retain upstream attribution",
        "source_pdf_count": len(full_rows), "source_pdf_metadata": full_rows,
        "derived_case_count": len(variant_rows),
        "derived_cases_are_text_edits_not_forged_pdf_images": True,
        "adjudicated_real_fraud_documents": 0,
        "publisher_transaction_level_ground_truth_public": False,
        "source_group_count": len(originals),
        "independent_real_fraud_test_split": False,
        "baseline_results": {
            mode: rates(variant_rows, [
                classify(row["text"], originals[row["source_id"]], mode)
                for row in variant_rows
            ]) for mode in ("full_original", "first_30_tokens", "no_source")
        },
        "exclusions": exclusions,
        "limitations": [
            "All source PDFs themselves are synthetic third-party creations",
            "Only five document origins; all derived cases share their sources",
            "The full-original comparator has an exact source text oracle by construction",
            "The test does not establish transaction extraction accuracy without withheld answers",
            "Controlled text edits are not altered/forged PDF image pixels",
            "No independently adjudicated real financial fraud labels",
            "No GPT or Graph-RAG advantage measured in this source validation",
        ]
    }
    with (out/"sources.json").open("w", encoding="utf8") as f:
        json.dump(full_rows, f, indent=2)
    with (out/"v3_predictions.csv").open("w", newline="", encoding="utf8") as f:
        w = csv.DictWriter(f, fieldnames=list(predictions[0]))
        w.writeheader()
        w.writerows(predictions)
    # Not exporting extracted raw contents or repackaging third-party PDFs.
    with (out/"v3_results.json").open("w", encoding="utf8") as f:
        json.dump(summary, f, indent=2)
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
